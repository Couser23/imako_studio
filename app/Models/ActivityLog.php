<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

class ActivityLog extends Model
{
    protected $guarded = [];

    protected $casts = [
        'metadata' => 'array',
    ];

    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /**
     * Helper to quickly log an activity.
     */
    public static function log(string $action, string $title, ?string $description = null, ?array $metadata = null): static
    {
        return static::create([
            'user_id' => auth()->id(),
            'action' => $action,
            'title' => $title,
            'description' => $description,
            'metadata' => $metadata,
            'ip_address' => request()->ip(),
            'user_agent' => request()->userAgent(),
        ]);
    }

    /**
     * Get the icon color based on action type.
     */
    public function getIconColorAttribute(): string
    {
        return match ($this->action) {
            'login' => 'green',
            'confirm_payment' => 'emerald',
            'assign_employee' => 'purple',
            'update_setting' => 'gray',
            'create_package' => 'yellow',
            'reject_payment' => 'red',
            'cancel_booking' => 'red',
            default => 'blue',
        };
    }

